#!/usr/bin/env python3
"""Generate every per-agent file from the neutral source in agent/.

agent/ is the only place agent-facing files are edited. This script renders each target into a
{repo-relative path: bytes} map, writes it, or --check's it against the tree (CI runs --check).

Plan 1 has one target, "claude", whose output is today's .claude/, CLAUDE.md and AGENTS.md plus a
one-line header. JSON and .example files carry no header (no comment syntax); the drift check
covers them anyway.

Run it in the toolkit REPO, not in an installed copy. setup.sh fills placeholders in an installed
copy: --check reports that as drift on purpose, and write mode refuses to run there (exit 2),
because regenerating would put every placeholder back and leave the hooks unconfigured.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
# Installed copies carry these headers too, so they speak to both readers: a contributor edits the
# source; a user keeps personal notes in KNOWLEDGEBASE.local.md, which updates never replace.
MD_HEADER = ("<!-- GENERATED by scripts/gen_agent_trees.py from {src}. Toolkit contributors: edit the source. "
             "Your own notes belong in KNOWLEDGEBASE.local.md, which updates never replace. -->\n")
SH_HEADER = ("# GENERATED by scripts/gen_agent_trees.py from {src}. Toolkit contributors: edit the source;"
             " setup.sh configures this installed copy.\n")
OWNED_DIRS = (".claude/skills", ".claude/hooks")
TEXT_SUFFIXES = {".md", ".sh"}
# Codex truncates AGENTS.md past this many bytes, SILENTLY (spec E7). CI fails above it (D9); the
# 65536 project_doc_max_bytes in .codex/config.toml (Plan 4) is margin only, and only in a trusted dir.
INSTRUCTION_BUDGET = 32768
# Room held for agent/instructions/codex.md until it exists; then its real size is used instead.
CODEX_ADDENDUM_RESERVE = 2048
# setup.sh fills {{GAME_ROOT}} & co. and splices the MO2 block into the INSTALLED copy -- the file an
# agent actually reads. Sized by tests/test_instruction_budget.py against the real setup.sh.
INSTALL_EXPANSION_RESERVE = 2560
NOT_ADDENDA = ("core.md", "agents-pointer.md")


def _lf(data: bytes) -> bytes:
    return data.replace(b"\r\n", b"\n")


def _headed(src_label: str, data: bytes, suffix: str) -> bytes:
    if suffix not in TEXT_SUFFIXES:
        return data
    text = _lf(data).decode("utf-8")
    if suffix == ".sh":
        first, _, rest = text.partition("\n")
        return (first + "\n" + SH_HEADER.format(src=src_label) + rest).encode("utf-8")
    header = MD_HEADER.format(src=src_label)
    if text.startswith("---\n"):
        close = text.find("\n---\n", 3)
        if close != -1:
            end = close + len("\n---\n")
            return (text[:end] + header + text[end:]).encode("utf-8")
    return (header + text).encode("utf-8")


def instruction_sizes(src: Path) -> dict[str, int]:
    """Worst-case INSTALLED bytes of header + core + each addendum (LF, as generated)."""
    ins = src / "instructions"
    core = _lf((ins / "core.md").read_bytes())
    sizes: dict[str, int] = {}
    for f in sorted(ins.glob("*.md")):
        if f.name in NOT_ADDENDA:
            continue
        body = _headed(f"agent/instructions/core.md + {f.name}", core + _lf(f.read_bytes()), ".md")
        sizes[f.name] = len(body) + INSTALL_EXPANSION_RESERVE
    if "codex.md" not in sizes:
        body = _headed("agent/instructions/core.md + codex.md", core, ".md")
        sizes["codex.md (reserved)"] = len(body) + CODEX_ADDENDUM_RESERVE + INSTALL_EXPANSION_RESERVE
    return sizes


def budget_problems(src: Path) -> list[str]:
    return [f"core.md + {name}: {n} bytes installed (worst case) > {INSTRUCTION_BUDGET} -- Codex silently "
            f"truncates AGENTS.md past this. Move bulk into a skill or docs/ (agent/README.md)."
            for name, n in sorted(instruction_sizes(src).items()) if n > INSTRUCTION_BUDGET]


def _render_claude(src: Path) -> dict[str, bytes]:
    ins = src / "instructions"
    out: dict[str, bytes] = {
        "CLAUDE.md": _headed("agent/instructions/core.md + claude.md",
                             _lf((ins / "core.md").read_bytes()) + _lf((ins / "claude.md").read_bytes()), ".md"),
        "AGENTS.md": _headed("agent/instructions/agents-pointer.md", (ins / "agents-pointer.md").read_bytes(), ".md"),
    }
    for f in sorted((src / "skills").rglob("*")):
        if f.is_file():
            rel = f.relative_to(src / "skills").as_posix()
            out[f".claude/skills/{rel}"] = _headed(f"agent/skills/{rel}", f.read_bytes(), f.suffix)
    for f in sorted((src / "guards" / "adapters" / "claude").glob("*.sh")):
        out[f".claude/hooks/{f.name}"] = _headed(f"agent/guards/adapters/claude/{f.name}", f.read_bytes(), ".sh")
    for f in sorted((src / "targets" / "claude").iterdir()):
        if f.is_file():
            out[f".claude/{f.name}"] = _lf(f.read_bytes())
    return out


TARGETS = {"claude": _render_claude}


def render(target: str, src: Path) -> dict[str, bytes]:
    return TARGETS[target](src)


def write(outputs: dict[str, bytes], root: Path) -> list[str]:
    changed = []
    for rel, data in outputs.items():
        p = root / rel
        if p.exists() and p.read_bytes() == data:
            continue
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
        changed.append(rel)
    return changed


def configured_by_setup(outputs: dict[str, bytes], root: Path) -> list[str]:
    """Generated files whose placeholders setup.sh has filled -- the mark of an installed copy."""
    found = []
    for rel, data in sorted(outputs.items()):
        p = root / rel
        if b"{{" in data and p.is_file() and b"{{" not in p.read_bytes():
            found.append(rel)
    return found


def check(outputs: dict[str, bytes], root: Path) -> list[str]:
    problems = []
    configured = set(configured_by_setup(outputs, root))
    for rel, data in sorted(outputs.items()):
        p = root / rel
        if not p.exists():
            problems.append(f"{rel}: missing -- run: python scripts/gen_agent_trees.py")
            continue
        have = p.read_bytes()
        if have == data:
            continue
        if rel in configured:
            problems.append(f"{rel}: differs, and its placeholders are filled -- this looks like an installed "
                            f"copy that setup.sh configured; run --check in the toolkit repo instead")
        else:
            problems.append(f"{rel}: differs from its source -- edit agent/, then run: python scripts/gen_agent_trees.py")
    for owned in OWNED_DIRS:
        base = root / owned
        if base.is_dir():
            for f in sorted(base.rglob("*")):
                rel = f.relative_to(root).as_posix()
                if f.is_file() and rel not in outputs:
                    problems.append(f"{rel}: not generated -- add it under agent/ or delete it")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--target", default="claude", choices=sorted(TARGETS))
    ap.add_argument("--check", action="store_true", help="report drift, write nothing")
    ap.add_argument("--root", type=Path, default=REPO)
    ap.add_argument("--budget", action="store_true", help="report instruction sizes vs the budget")
    a = ap.parse_args(argv)
    if a.budget:
        for name, n in sorted(instruction_sizes(a.root / "agent").items()):
            print(f"core.md + {name}: {n} / {INSTRUCTION_BUDGET} bytes (headroom {INSTRUCTION_BUDGET - n})")
        problems = budget_problems(a.root / "agent")
        print("\n".join(problems) if problems else "within budget")
        return 1 if problems else 0
    outputs = render(a.target, a.root / "agent")
    if a.check:
        problems = check(outputs, a.root)
        print("\n".join(problems) if problems else f"in sync: {len(outputs)} generated files ({a.target})")
        return 1 if problems else 0
    configured = configured_by_setup(outputs, a.root)
    if configured:
        print("REFUSED: this looks like an installed copy that setup.sh configured "
              f"({', '.join(configured)}). Regenerating would put every placeholder back and leave the "
              "hooks unconfigured, so they would refuse every command. Nothing was written. To change an "
              "installed copy, edit its files directly or re-extract the release and run setup.sh; to "
              "change the toolkit, edit agent/ in a clone of the repository.")
        return 2
    changed = write(outputs, a.root)
    print(f"wrote {len(changed)} of {len(outputs)} files ({a.target})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
