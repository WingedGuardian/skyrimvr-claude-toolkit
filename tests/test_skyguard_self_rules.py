GAME = "C:/GOG Games/The Elder Scrolls V Skyrim VR"
SHELL = {"Bash": "bash", "PowerShell": "powershell"}
NOHOME = tempfile.mkdtemp(prefix="p6t12-nohome-")
ENV0 = {"USERPROFILE": NOHOME, "HOME": NOHOME}
SELF_IDS = ("S-SELF-STATE", "S-SELF-GUARD", "W-SELF-STATE", "W-SELF-GUARD")


def _rows():
    text = (REPO / "tests" / "guard_corpus" / "intended.jsonl").read_text(encoding="utf-8")
    return [r for r in (json.loads(x) for x in text.split("\n") if x.strip()) if r["task"] == "P6-T12"]


ROWS = _rows()


def _audit():
    a = audit.Audit("")
    a.raw = lambda line: None
    return a


def _got(v):
    if v.decision == "allow":
        return ("advise", v.context) if v.context else ("allow", "")
    return (v.decision, v.reason)


def _roots():
    return paths.roots("C:/p6t12/Skyrim VR", "", {"SKYRIM_GAME_ROOT": GAME})


def shell(command, shell_name="bash", cwd=GAME, env=None):
    a = _audit()
    v = shell_rules.decide(command, _roots(), a, cwd=cwd, shell=shell_name, env=ENV0 if env is None else env)
    return _got(v), {rid for rid, _ in a.fired}


def write(path, cwd=GAME, env=None, roots="default"):
    a = _audit()
    v = write_rules.decide(path, a, roots=_roots() if roots == "default" else roots, cwd=cwd,
                           env=ENV0 if env is None else env)
    return _got(v), {rid for rid, _ in a.fired}


def test_there_are_rows_for_every_rule_and_both_directions():
    assert len(ROWS) >= 50, len(ROWS)
    fired = set().union(*(set(r["rules"]) for r in ROWS))
    assert set(SELF_IDS) <= fired
    assert sum(r["decision"] == "allow" for r in ROWS) >= 15


@pytest.mark.parametrize("row", ROWS, ids=[r["id"] for r in ROWS])
def test_p6t12_row(row):
    p = row["payload"]
    cwd = (p.get("cwd") or "").replace("<install>", GAME)
    if p["tool_name"] in SHELL:
        got, fired = shell(p["tool_input"]["command"].replace("<install>", GAME), SHELL[p["tool_name"]], cwd)
    else:
        got, fired = write(p["tool_input"]["file_path"].replace("<install>", GAME), cwd)
    assert got == (row["decision"], row["text"])
    assert fired == set(row["rules"])


