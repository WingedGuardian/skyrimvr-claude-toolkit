# ---- GUARD-FILES.sha256 (generated, drift-gated) -------------------------------------------------------------------

def _gen():
    spec = importlib.util.spec_from_file_location("gen_guard_hashes", REPO / "scripts" / "gen-guard-hashes.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def test_the_committed_manifest_is_current():
    """The drift gate: a guard file changed without regenerating GUARD-FILES.sha256 fails here and in CI."""
    gen = _gen()
    have = (REPO / gen.MANIFEST).read_text(encoding="utf-8")
    assert have == gen.render(), "run: python scripts/gen-guard-hashes.py"


def test_the_manifest_names_exactly_the_tracked_guard_files():
    gen = _gen()
    names = gen.guard_files()
    assert "tools/skyguard/engine.py" in names and ".claude/hooks/protect-bash.sh" in names
    assert ".claude/settings.json" in names and ".codex/hooks/skyguard-entry.ps1" in names
    assert ".codex/hooks.json" not in names                            # setup.sh rewrites it on every install
    assert not [n for n in names if n.startswith(".claude/skills/")]
    assert all(self_rules.install_kind(n.lower().split("/")) == self_rules.GUARD for n in names)


def test_the_session_banner_reads_the_generated_manifest(tmp_path):
    """The format the generator writes is the one session.py reads: a clean copy is silent, an edit is named."""
    gen = _gen()
    text = gen.render()
    root = tmp_path / "inst"
    for line in text.splitlines()[1:]:
        rel = line.split("  ", 1)[1]
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(str(REPO / rel), str(root / rel))
    (root / gen.MANIFEST).write_text(text, encoding="utf-8")
    release, differ, missing, unchecked = session._guard_drift(str(root))
    assert (differ, missing, unchecked) == ([], 0, [])
    assert release == gen.release()
    with open(str(root / ".claude" / "hooks" / "protect-bash.sh"), "a", encoding="utf-8") as fh:
        fh.write("\nexit 0\n")
    assert session._guard_drift(str(root))[1] == ["protect-bash.sh"]
    assert gen.verify(root) == ["differs: .claude/hooks/protect-bash.sh"]


def test_the_check_mode_fails_on_a_stale_manifest(tmp_path, monkeypatch, capsys):
    gen = _gen()
    stale = tmp_path / "repo"
    stale.mkdir()
    monkeypatch.setattr(gen, "REPO", stale)
    monkeypatch.setattr(gen, "render", lambda repo=None: "# release 9.9.9\n")
    (stale / gen.MANIFEST).write_text("# release 0.0.1\n", encoding="utf-8")
    assert gen.main(["--check"]) == 1
    (stale / gen.MANIFEST).write_text("# release 9.9.9\n", encoding="utf-8")
    assert gen.main(["--check"]) == 0


def test_the_ci_workflow_runs_the_drift_gate():
    ci = (REPO / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
    assert "scripts/gen-guard-hashes.py --check" in ci
    rel = (REPO / ".github" / "workflows" / "release.yml").read_text(encoding="utf-8")
    assert "gen-guard-hashes.py --verify" in rel

