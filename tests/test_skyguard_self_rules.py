H = 3600.0
NOW = 1_800_000_000.0
SID = "sess-p6t12"


def _shadow_env(tmp_path):
    project, hb = tmp_path / "proj", tmp_path / "hb"
    project.mkdir()
    state.write(str(project / ".skyguard" / "state.json"), {"v": 1, "persistent": {}, "lifts": [
        {"kind": "guards", "reason": "t", "session_id": SID, "agent": "claude", "created": NOW - H,
         "expires_at": NOW + H}]})
    f = hb / "sessions" / (SID + ".log")
    f.parent.mkdir(parents=True)
    f.write_text("{:.6f} start startup t.jsonl\n".format(NOW - 2 * H), encoding="utf-8")
    return project, hb


@pytest.mark.parametrize("route", ["shell", "write"])
def test_guards_off_does_not_open_the_state_file(tmp_path, route):
    """Shadowed, `guards off` would let the agent then write state.json itself -- an unapproved persistent off."""
    project, hb = _shadow_env(tmp_path)
    if route == "shell":
        (decision, reason), _ = shell("echo x > .skyguard/state.json")
    else:
        (decision, reason), _ = write(GAME + "/.skyguard/state.json")
    assert decision == "deny"
    v = engine.shadow(codes.classify(Verdict(decision, reason)), str(project), SID, str(hb), audit.Audit(str(project)),
                      now=NOW)
    assert (v.decision, v.reason) == (decision, reason)
    assert "kept" in (project / ".claude" / "backups" / "AUDIT_LOG.txt").read_text(encoding="utf-8")


# ---- Codex apply_patch: Add / Update / Delete / Move, both ends of a Move -----------------------------------------

def _codex(body):
    raw = json.dumps({"hook_event_name": "PreToolUse", "tool_name": "apply_patch", "cwd": GAME,
                      "tool_input": {"command": "*** Begin Patch\n" + body + "\n*** End Patch"}})
    req = codex.to_request(raw, platform="win32")
    assert not req.failure, req.failure
    return engine.evaluate_writes(req, _audit(), roots=_roots())


@pytest.mark.parametrize("body", [
    "*** Add File: .skyguard/state.json\n+{}",
    "*** Update File: .skyguard/state.json\n@@\n-a\n+b",
    "*** Delete File: .skyguard/lock.json",
    "*** Update File: .skyguard/state.json\n*** Move to: C:/Temp/state.json\n@@\n-a\n+b",
], ids=["add", "update", "delete", "move-from"])
def test_apply_patch_into_the_state_is_denied(body):
    v = _codex(body)
    assert v.decision == "deny" and v.code == "write.W-SELF-STATE", v


def test_apply_patch_move_to_into_the_state_is_denied():
    """l2-self-applypatch-move: the `*** Move to:` destination is a path the patch writes."""
    v = _codex("*** Update File: notes.txt\n*** Move to: .skyguard/state.json\n@@\n-a\n+b")
    assert v.decision == "deny" and v.code == "write.W-SELF-STATE", v


def test_apply_patch_on_a_hook_is_the_priced_guard_rule():
    v = _codex("*** Update File: .codex/hooks/skyguard-entry.ps1\n@@\n-a\n+b")
    want = rules.RULES["W-SELF-GUARD"]["decision"]
    assert (v.decision if want == "ask" else ("advise" if v.context else v.decision)) == want
    assert "safety guards themselves" in (v.reason or v.context)


def test_apply_patch_elsewhere_is_untouched():
    v = _codex("*** Update File: notes.txt\n@@\n-a\n+b")
    assert v.decision == "allow" and not v.context


def test_on_codex_a_guard_ask_is_a_deny_and_a_state_deny_stays_one():
    for rid in ("S-SELF-GUARD", "S-SELF-STATE"):
        text = rules.message(rid, file="x")
        decision = rules.RULES[rid]["decision"]
        if decision == "advise":
            continue
        body = json.loads(codex.render(codes.classify(Verdict(decision, text))))["hookSpecificOutput"]
        assert body["permissionDecision"] == "deny"


