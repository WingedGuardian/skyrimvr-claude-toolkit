def _got(v):
    if v.decision == "allow":
        return ("advise", v.context) if v.context else ("allow", "")
    return (v.decision, v.reason)


def _roots():
    return paths.roots("C:/p6t12/Skyrim VR", "", {"SKYRIM_GAME_ROOT": GAME})


def shell(command, shell_name="bash", cwd=GAME, env=None):
    a = _audit()
    v = shell_rules.decide(command, _roots(), a, cwd=cwd, shell=shell_name, env=ENV0 if env is None else env)
    return _got(v), {rid for rid, _ in a.fired}


def write(path, cwd=GAME, env=None, roots="default"):
    a = _audit()
    v = write_rules.decide(path, a, roots=_roots() if roots == "default" else roots, cwd=cwd,
                           env=ENV0 if env is None else env)
    return _got(v), {rid for rid, _ in a.fired}


