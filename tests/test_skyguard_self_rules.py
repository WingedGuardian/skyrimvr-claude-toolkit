"""Plan 6 Task 12 (R12): agent self-protection.

  S-SELF-STATE / W-SELF-STATE  a write into the install's .skyguard/** by any route but the CLI -> deny (and guards off
                               never shadows it).
  S-SELF-GUARD / W-SELF-GUARD  a write into the guard code or config (hooks, settings*.json, skyrim-paths.env, .codex,
                               tools/skyguard, agent/guards, the heartbeat and audit log, the user-level hook switches)
                               -> priced (rules.RULES holds the decision; see the pricing doc's Task 12 Ruling).
  GUARD-FILES.sha256           generated by scripts/gen-guard-hashes.py, drift-gated here and in CI.

As in test_skyguard_lift_rules: every hand-authored P6-T12 intended row fired IN-PROCESS (decision, rule trace, exact
text; one test id per row so a mutation names the row it must turn red), then the routes the Claude corpus cannot
express (Codex apply_patch, a home folder distinct from the install), then one behaviour per test.
"""
