"""The Codex `.rules` file (Plan 4 Task 9; R5): the line that holds while the hooks are unapproved.

Codex runs project hooks only after the user approves them, but a `.rules` `forbidden` prefix rule blocks
regardless. So the rules file carries ONLY prefix rules that are strict subsets of an existing hook deny
(today just `reg delete`): a prefix rule can never refuse something the hooks would allow, and every other
verdict stays hook-only. Task 0 measured offline that `reg.exe delete` does NOT match a `reg delete`
prefix, so both spellings are listed. Task 10's generator consumes `render()`.

CLASSIFICATION covers every DENY_/ASK_/NO_ verdict constant of shell_rules; a new one fails
tests/test_codex_rules.py until it is classified here (Plan 5 trips this deliberately).
"""
from __future__ import annotations

import json
from typing import Dict, List, Tuple

CLASSIFICATION: Dict[str, Tuple[str, str]] = {
    "shell.DENY_REGISTRY": (
        "forbidden",
        "the hook denies every `reg delete`; `reg delete` / `reg.exe delete` prefixes are a strict subset"),
    "shell.DENY_CONFIG": ("hook_only", "path-based: the protected path is an argument, not a prefix"),
    "shell.DENY_INSTALL": ("hook_only", "path-based: the protected path is an argument, not a prefix"),
    "shell.DENY_CHAMPOLLION": ("hook_only", "path-based: the protected path is an argument, not a prefix"),
    "shell.DENY_PSC": ("hook_only", "the `-o` flag can be anywhere"),
    "shell.ASK_RESAVER": (
        "hook_only", "a prefix would also prompt every dry-run; `--apply` position varies (R4)"),
    "shell.NO_COMMAND_DENY": ("hook_only", "analysis failure, not a command"),
    "shell.NO_ROOT_DENY": ("hook_only", "analysis failure, not a command"),
}

_WHY = ("Skyrim toolkit: registry deletes are refused (Bethesda keys locate the game). "
        "Ask the user to run it themselves if it is really intended.")

PREFIX_RULES: List[dict] = [
    {"pattern": ["reg", "delete"], "decision": "forbidden", "code": "shell.DENY_REGISTRY",
     "justification": _WHY,
     "match": [["reg", "delete", "HKCU\\Software\\SkyguardProbe", "/f"]],
     "not_match": [["reg", "query", "HKCU\\Software"]]},
    {"pattern": ["reg.exe", "delete"], "decision": "forbidden", "code": "shell.DENY_REGISTRY",
     "justification": _WHY,
     "match": [["reg.exe", "delete", "HKCU\\Software\\SkyguardProbe", "/f"]],
     "not_match": [["reg.exe", "query", "HKCU\\Software"]]},
]


def _s(value) -> str:
    return json.dumps(value, ensure_ascii=True)


def render() -> str:
    out = ["# Generated by tools/skyguard/codex_rules.py -- do not edit.",
           "# Only prefix rules that are strict subsets of a hook deny; everything else is hook-only.", ""]
    for r in PREFIX_RULES:
        out.append("prefix_rule(")
        out.append("    pattern = {},".format(_s(r["pattern"])))
        out.append("    decision = {},".format(_s(r["decision"])))
        out.append("    justification = {},".format(_s(r["justification"])))
        out.append("    match = {},".format(_s(r["match"])))
        out.append("    not_match = {},".format(_s(r["not_match"])))
        out.append(")")
        out.append("")
    return "\n".join(out)
